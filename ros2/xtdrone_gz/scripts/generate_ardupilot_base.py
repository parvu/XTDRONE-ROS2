#!/usr/bin/env python3
"""Flat ArduPilot Iris base model for the XTDrone vehicle models (generate_vehicle_models.py).

ardupilot_gazebo's iris_with_ardupilot includes iris_with_standoffs as a nested model, so its links are
"iris_with_standoffs::base_link". The XTDrone sensor kits attach to "base_link" of the model they include (as with
PX4's x500), so this script writes models/iris_ardupilot with the same links, joints, rotor lift/drag and joint-state
plugins at the top level. The ArduPilotPlugin (SITL link) is added by generate_vehicle_models.py to each vehicle,
because its FDM port depends on the instance. Meshes stay in ardupilot_gazebo (model://iris_with_standoffs/...).

  python3 generate_ardupilot_base.py [out_dir]       (default: ../models)
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
SRC = REPO / "ardupilot_gazebo" / "models"
PREFIX = "iris_with_standoffs::"


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "models"
    standoffs = ET.parse(SRC / "iris_with_standoffs/model.sdf").getroot().find("model")
    wrapper = ET.parse(SRC / "iris_with_ardupilot/model.sdf").getroot().find("model")
    parts = []
    for el in standoffs:
        if el.tag in ("link", "joint"):
            parts.append(ET.tostring(el, encoding="unicode"))
    for el in wrapper.findall("plugin"):
        if el.get("name") in ("gz::sim::systems::LiftDrag", "gz::sim::systems::JointStatePublisher"):
            parts.append(ET.tostring(el, encoding="unicode").replace(PREFIX, ""))
    body = re.sub(r"\n\s*\n", "\n", "\n    ".join(p.strip() for p in parts))
    sdf = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by xtdrone_gz/scripts/generate_ardupilot_base.py from ardupilot_gazebo's iris_with_standoffs. Do not edit. -->
<sdf version="1.9">
  <model name="iris_ardupilot">
    {body}
  </model>
</sdf>
"""
    d = out / "iris_ardupilot"
    d.mkdir(parents=True, exist_ok=True)
    (d / "model.sdf").write_text(sdf)
    (d / "model.config").write_text("""<?xml version="1.0"?>
<model>
  <name>iris_ardupilot</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author><name>XTDrone</name></author>
  <description>ArduPilot Iris (ardupilot_gazebo iris_with_standoffs) with its links at the top level, base of the XTDrone iris models.</description>
</model>
""")
    print(f"generated {d}")


if __name__ == "__main__":
    main()
