#!/usr/bin/env python3
"""Flat ArduPilot Iris base model for the XTDrone vehicle models (generate_vehicle_models.py).

ardupilot_gazebo's iris_with_ardupilot includes iris_with_standoffs as a nested model, so its links are
"iris_with_standoffs::base_link". The XTDrone sensor kits attach to "base_link" of the model they include (as with
PX4's x500), so this script writes models/iris_ardupilot with the same links, joints, rotor lift/drag and joint-state
plugins at the top level. The ArduPilotPlugin (SITL link) is added by generate_vehicle_models.py to each vehicle,
because its FDM port depends on the instance. Meshes stay in ardupilot_gazebo (model://iris_with_standoffs/...).

  python3 generate_ardupilot_base.py [out_dir]       (default: ../models)
"""
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]
SRC = REPO / "ardupilot_gazebo" / "models"
PREFIX = "iris_with_standoffs::"


def plane_base(out):
    """Flat plane_ardupilot base from ardupilot_gazebo's zephyr (flying wing): its links and joints at the top level and
    the zephyr_with_ardupilot rotor/wing aerodynamics, without the nested model name (the plugin is added per vehicle)."""
    zephyr = ET.parse(SRC / "zephyr/model.sdf").getroot().find("model")
    wrapper = ET.parse(SRC / "zephyr_with_ardupilot/model.sdf").getroot().find("model")
    # no wheels: the belly slides. The wing mesh as a collision shape rests the plane 17 degrees nose down (and it is
    # slow): a flat box with little friction takes its place.
    for link in zephyr.iter("link"):  # the spinning blades (+-0.15 m) and the rudders (0.06 m below the belly) would hit the ground and throw the plane around
        for c in link.findall("collision"):
            if c.get("name") in ("blade1", "blade2", "right_rudder_collision", "left_rudder_collision"):
                link.remove(c)
    for c in zephyr.iter("collision"):
        if c.get("name") == "body_collision":
            for child in list(c):
                c.remove(child)
            c.append(ET.fromstring("<pose>0 0 -0.01 0 0 0</pose>"))
            c.append(ET.fromstring("<geometry><box><size>1.5 0.45 0.04</size></box></geometry>"))
            c.append(ET.fromstring("<surface><friction><ode><mu>0.05</mu><mu2>0.05</mu2></ode></friction></surface>"))
    parts = [ET.tostring(el, encoding="unicode") for el in zephyr if el.tag in ("link", "joint")]
    for el in wrapper.findall("plugin"):
        if el.get("name") != "ArduPilotPlugin":
            parts.append(ET.tostring(el, encoding="unicode").replace("zephyr::", ""))
    body = re.sub(r"\n\s*\n", "\n", "\n    ".join(p.strip() for p in parts))
    sdf = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by xtdrone_gz/scripts/generate_ardupilot_base.py from ardupilot_gazebo's zephyr. Do not edit. -->
<sdf version="1.9">
  <model name="plane_ardupilot">
    {body}
  </model>
</sdf>
"""
    d = out / "plane_ardupilot"
    d.mkdir(parents=True, exist_ok=True)
    (d / "model.sdf").write_text(sdf)
    (d / "model.config").write_text("""<?xml version="1.0"?>
<model>
  <name>plane_ardupilot</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author><name>XTDrone</name></author>
  <description>ArduPilot Zephyr flying wing with its links at the top level, base of the XTDrone plane model.</description>
</model>
""")
    print(f"generated {d}")


def rover_base(out):
    """Flat rover_ardupilot base from SITL_Models' r1_rover (models/r1_rover, vendored): the links, wheel joints and
    motor plugins, without its own ArduPilotPlugin (added per vehicle, the FDM port depends on the instance) and its
    OdometryPublisher (XTDrone's ground truth is added to every vehicle)."""
    src = ET.parse(out / "r1_rover/model.sdf").getroot().find("model")
    parts = []
    for el in src:
        if el.tag in ("link", "joint"):
            parts.append(ET.tostring(el, encoding="unicode"))
        elif el.tag == "plugin" and el.get("name") not in ("ArduPilotPlugin", "gz::sim::systems::OdometryPublisher"):
            parts.append(ET.tostring(el, encoding="unicode"))
    body = re.sub(r"\n\s*\n", "\n", "\n    ".join(p.strip() for p in parts))
    sdf = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by xtdrone_gz/scripts/generate_ardupilot_base.py from models/r1_rover (SITL_Models). Do not edit. -->
<sdf version="1.9">
  <model name="rover_ardupilot">
    {body}
  </model>
</sdf>
"""
    d = out / "rover_ardupilot"
    d.mkdir(parents=True, exist_ok=True)
    (d / "model.sdf").write_text(sdf)
    (d / "model.config").write_text("""<?xml version="1.0"?>
<model>
  <name>rover_ardupilot</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author><name>XTDrone</name></author>
  <description>SITL_Models' R1 rover with its links at the top level, base of the XTDrone rover models.</description>
</model>
""")
    print(f"generated {d}")


def sitl_model_base(out, model, base):
    """Flat <base> model from a SITL_Models Gazebo model (SITL_Models/ at the repo root, fetched by
    scripts/build_ardupilot.sh): its links, joints and lift/drag plugins without the ArduPilotPlugin (added per vehicle,
    the FDM port depends on the instance) and its OdometryPublisher. The meshes stay in SITL_Models (model://<model>)."""
    path = REPO / "SITL_Models/Gazebo/models" / model / "model.sdf"
    if not path.is_file():
        raise SystemExit(f"{path} is missing: run scripts/build_ardupilot.sh")
    src = ET.parse(path).getroot().find("model")
    parts = []
    for el in src:
        if el.tag in ("link", "joint"):
            parts.append(ET.tostring(el, encoding="unicode"))
        elif el.tag == "plugin" and el.get("name") not in ("ArduPilotPlugin", "gz::sim::systems::OdometryPublisher"):
            parts.append(ET.tostring(el, encoding="unicode"))
    body = re.sub(r"\n\s*\n", "\n", "\n    ".join(p.strip() for p in parts))
    sdf = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by xtdrone_gz/scripts/generate_ardupilot_base.py from SITL_Models' {model}. Do not edit. -->
<sdf version="1.9">
  <model name="{base}">
    {body}
  </model>
</sdf>
"""
    d = out / base
    d.mkdir(parents=True, exist_ok=True)
    (d / "model.sdf").write_text(sdf)
    (d / "model.config").write_text(f"""<?xml version="1.0"?>
<model>
  <name>{base}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author><name>XTDrone</name></author>
  <description>SITL_Models' {model} with its links at the top level, base of the XTDrone {base} models.</description>
</model>
""")
    print(f"generated {d}")


def write_iris(out, name, standoffs_path, wrapper, collisions, bumper, imu_flu):
    standoffs = ET.parse(standoffs_path).getroot().find("model")
    for link in standoffs.findall("link"):
        for col in link.findall("collision"):
            link.remove(col)
        if link.get("name") == "base_link":
            for k, col in enumerate(collisions):
                link.insert(list(link).index(link.find("visual")) + k, ET.fromstring(col))
            link.append(bumper)
            link.append(imu_flu)
    parts = []
    for el in standoffs:
        if el.tag in ("link", "joint"):
            parts.append(ET.tostring(el, encoding="unicode"))
    for el in wrapper.findall("plugin"):
        if el.get("name") in ("gz::sim::systems::LiftDrag", "gz::sim::systems::JointStatePublisher"):
            parts.append(ET.tostring(el, encoding="unicode").replace(PREFIX, ""))
    body = re.sub(r"\n\s*\n", "\n", "\n    ".join(p.strip() for p in parts))
    sdf = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by xtdrone_gz/scripts/generate_ardupilot_base.py from ardupilot_gazebo's iris_with_standoffs. Do not edit. -->
<sdf version="1.9">
  <model name="{name}">
    {body}
  </model>
</sdf>
"""
    d = out / name
    d.mkdir(parents=True, exist_ok=True)
    (d / "model.sdf").write_text(sdf)
    (d / "model.config").write_text(f"""<?xml version="1.0"?>
<model>
  <name>{name}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <author><name>XTDrone</name></author>
  <description>ArduPilot Iris (ardupilot_gazebo iris_with_standoffs) with its links at the top level, base of the XTDrone iris models.</description>
</model>
""")
    print(f"generated {d}")


def main():
    out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent / "models"
    wrapper = ET.parse(SRC / "iris_with_ardupilot/model.sdf").getroot().find("model")
    # One box for the whole frame, legs included (x -0.16..0.145, y -0.235..0.24, z -0.195..0.04), instead of the
    # mesh body, four leg cylinders and four rotor discs of the ArduPilot model: gz-sim's contact solver cost grows
    # with the number of collision shapes and nine vehicles on the ground ran at 0.4 of real time with them, 1.4 with
    # the box. A contact sensor on it reports ground and obstacle contacts (XTDrone's benchmarker/collision, chapter 44).
    contact = "<surface><contact><ode><max_vel>100.0</max_vel><min_depth>0.001</min_depth></ode></contact></surface>"
    body_box = f"""
      <collision name="base_collision">
        <pose>-0.007 0.002 -0.075 0 0 0</pose>
        <geometry><box><size>0.31 0.47 0.24</size></box></geometry>
        {contact}
      </collision>"""
    bumper = ET.fromstring("""
      <sensor name="bumper" type="contact">
        <always_on>1</always_on>
        <update_rate>30</update_rate>
        <contact><collision>base_collision</collision></contact>
      </sensor>""")
    # The ArduPilot IMU (imu_link) is turned 180 degrees about x for the FRD frame; XTDrone's imu_gazebo (VINS-Fusion,
    # Cartographer, the attitude demo) wants a FLU IMU, like PX4's x500 had on base_link.
    imu_flu = ET.fromstring("""
      <sensor name="imu_flu" type="imu">
        <always_on>1</always_on>
        <update_rate>250</update_rate>
        <gz_frame_id>base_link</gz_frame_id>
      </sensor>""")
    plate = f"""
      <collision name="base_collision">
        <pose>-0.01 0.002 0.01 0 0 0</pose>
        <geometry><box><size>0.24 0.47 0.06</size></box></geometry>
        {contact}
      </collision>"""
    legs = [plate] + [f"""
      <collision name="leg_{i}">
        <pose>{x} {y} -0.1 0 0 0</pose>
        <geometry><box><size>0.02 0.02 0.19</size></box></geometry>
        {contact}
      </collision>""" for i, (x, y) in enumerate((x, y) for x in (-0.14, 0.13) for y in (-0.2, 0.2))]
    write_iris(out, "iris_ardupilot", SRC / "iris_with_standoffs/model.sdf", wrapper, [body_box], bumper, imu_flu)
    # iris_arm (chapter 33): the arm and the cube are under the body, between the landing legs: a thin body plate and
    # four legs instead of the box that fills the space below; shorter in x than the iris: the table stands 0.15 m
    # in front of the plate
    write_iris(out, "iris_legs_ardupilot", SRC / "iris_with_standoffs/model.sdf", wrapper, legs, bumper, imu_flu)
    plane_base(out)
    rover_base(out)
    if (REPO / "SITL_Models").is_dir():
        sitl_model_base(out, "skywalker_x8_quad", "vtol_ardupilot")
        sitl_model_base(out, "swan_k1_hwing", "tailsitter_ardupilot")


if __name__ == "__main__":
    main()
