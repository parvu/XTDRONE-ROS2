#!/usr/bin/env python3
"""Write the XTDrone 'sandisland' world (chapter 32) from VRX's sydney_regatta.sdf.

XTDrone's Classic sandisland.launch used VRX's sand island. In VRX v3 (Gazebo Harmonic) that is
sydney_regatta. PX4 multirotors also need the AirPressure system (barometer), which the VRX world
lacks; it is added here. The world keeps its name (sydney_regatta), so VRX's spawn launch and
wave settings work unchanged.

Usage: make_sandisland.py <vrx_gz/worlds/sydney_regatta.sdf> <out_dir>
"""
import sys
import xml.etree.ElementTree as ET
from pathlib import Path


def main():
    src, out = Path(sys.argv[1]), Path(sys.argv[2])
    tree = ET.parse(src)
    world = tree.getroot().find("world")
    names = {p.get("name") for p in world.findall("plugin")}
    if "gz::sim::systems::AirPressure" not in names:
        world.append(ET.fromstring('<plugin filename="gz-sim-air-pressure-system" '
                                   'name="gz::sim::systems::AirPressure"/>'))
    out.mkdir(parents=True, exist_ok=True)
    text = ET.tostring(tree.getroot(), encoding="unicode")
    (out / "sandisland.sdf").write_text(
        '<?xml version="1.0" ?>\n<!-- Generated by xtdrone_gz/scripts/make_sandisland.py from VRX '
        "sydney_regatta.sdf (+ AirPressure for PX4). -->\n" + text + "\n")
    print("wrote", out / "sandisland.sdf")


if __name__ == "__main__":
    main()
