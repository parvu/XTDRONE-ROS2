#!/usr/bin/env python3
"""Generate the Gazebo model iris_arm (chapter 33) in xtdrone_gz/models from urdf/iris_arm.urdf.xacro.

The model merges the ArduPilot iris (iris_ardupilot) (the iris of XTDrone) and adds the le_arm under its body, converted from the URDF
with `gz sdf -p`, plus
- the camera that looks at the object (camera_link),
- a DetachableJoint between the gripper and the object of the grasping world (coke_can_box_model). The ROS 1
  version held the object with gazebo_grasp_fix (contact forces); here grasping_demo attaches and detaches it on
  /model/<name>/detachable_joint/{attach,detach}.
gz_ros2_control is not in the model: it needs the path of its parameters file and the vehicle's namespace, which
robotic_arm.launch.py knows; the launch adds it to the running model (Gazebo's entity/system/add service).
Run it after changing the URDF: generate_iris_arm_model.py [xtdrone_gz/models]
"""
import re
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "xtdrone_gz" / "scripts"))
from generate_vehicle_models import ardupilot_copter_plugin  # noqa: E402

PKG = Path(__file__).resolve().parents[1]
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else PKG.parent / "xtdrone_gz" / "models"
NAME = "iris_arm"


def urdf_text():
    """xacro without needing the package installed: resolve $(find xtdrone_robotic_arm) to this directory."""
    with tempfile.TemporaryDirectory() as tmp:
        (Path(tmp) / "urdf").mkdir()
        for f in (PKG / "urdf").glob("*.xacro"):
            (Path(tmp) / "urdf" / f.name).write_text(f.read_text().replace("$(find xtdrone_robotic_arm)", tmp))
        return subprocess.run(["xacro", str(Path(tmp) / "urdf" / "iris_arm.urdf.xacro")], check=True,
                              capture_output=True, text=True).stdout


def arm_sdf(urdf):
    # keep the fixed joints (arm base, camera) as links: the URDF converter would lump them into base_link,
    # which is the iris's body here
    keep = "".join(f'<gazebo reference="{j}"><preserveFixedJoint>true</preserveFixedJoint></gazebo>'
                   for j in ("arm_base_joint", "camera_joint"))
    urdf = urdf.replace("</robot>", keep + "</robot>")
    # the converter drops a root link without mass (and its fixed children); base_link is dropped later anyway
    urdf = re.sub(r'<link name="base_link"\s*/>', '<link name="base_link"><inertial><mass value="1"/><inertia ixx="1" '
                  'ixy="0" ixz="0" iyy="1" iyz="0" izz="1"/></inertial></link>', urdf)
    with tempfile.NamedTemporaryFile("w", suffix=".urdf") as f:
        f.write(urdf)
        f.flush()
        sdf = subprocess.run(["gz", "sdf", "-p", f.name], check=True, capture_output=True, text=True).stdout
    return ET.fromstring(sdf).find("model")


CAMERA = """
      <sensor name="camera" type="camera">
        <always_on>1</always_on>
        <update_rate>15</update_rate>
        <gz_frame_id>camera_link</gz_frame_id>
        <camera>
          <horizontal_fov>1.5</horizontal_fov>
          <image><width>640</width><height>480</height><format>R8G8B8</format></image>
          <clip><near>0.02</near><far>50</far></clip>
        </camera>
      </sensor>"""

PLUGINS = """
    <plugin filename="gz-sim-detachable-joint-system" name="gz::sim::systems::DetachableJoint">
      <parent_link>gripper_base_link</parent_link>
      <child_model>coke_can_box_model</child_model>
      <child_link>coke_can</child_link>
      <suppress_child_warning>true</suppress_child_warning>
    </plugin>
    <plugin filename="gz-sim-odometry-publisher-system" name="gz::sim::systems::OdometryPublisher">
      <dimensions>3</dimensions>
      <odom_publish_frequency>50</odom_publish_frequency>
      <!-- PX4's gz_bridge reads /model/<name>/odometry_with_covariance (the default topic) as external
           vision. This is ground truth for ROS only (/<name>/ground_truth/odom): keep it away from PX4. -->
      <odom_covariance_topic>/xtdrone/ground_truth_with_covariance_unused</odom_covariance_topic>
    </plugin>"""

BRIDGE = """# Generated by xtdrone_robotic_arm/scripts/generate_iris_arm_model.py
base_model: iris_legs_ardupilot
bridges:
- gz_topic: /world/{world}/model/{name}/link/camera_link/sensor/camera/image
  ros_topic: le_arm/camera/image_raw
  ros_type: sensor_msgs/msg/Image
  gz_type: gz.msgs.Image
- gz_topic: /world/{world}/model/{name}/link/camera_link/sensor/camera/camera_info
  ros_topic: le_arm/camera/camera_info
  ros_type: sensor_msgs/msg/CameraInfo
  gz_type: gz.msgs.CameraInfo
- gz_topic: /model/{name}/detachable_joint/attach
  ros_topic: le_arm/gripper/attach
  ros_type: std_msgs/msg/Empty
  gz_type: gz.msgs.Empty
  direction: ROS_TO_GZ
- gz_topic: /model/{name}/detachable_joint/detach
  ros_topic: le_arm/gripper/detach
  ros_type: std_msgs/msg/Empty
  gz_type: gz.msgs.Empty
  direction: ROS_TO_GZ
- gz_topic: /model/{name}/detachable_joint/state
  ros_topic: le_arm/gripper/state
  ros_type: std_msgs/msg/String
  gz_type: gz.msgs.StringMsg
"""


def main():
    arm = arm_sdf(urdf_text())
    parts = []
    for el in arm:
        if el.tag == "link" and el.get("name") == "base_link":
            continue  # the iris's body
        # (poses are relative to the joints, the first joint's to base_link, which the iris provides)
        if el.tag == "link" and el.get("name") == "camera_link":
            el.append(ET.fromstring(CAMERA))
        if el.tag == "link":
            # no collisions: the arm under the iris would touch the ground and the table, and the grasp is a
            # joint (DetachableJoint), not friction. MoveIt checks the arm's collisions itself.
            for c in el.findall("collision"):
                el.remove(c)
        if el.tag == "joint":
            # DART has no mimic constraints (Gazebo logs an error); gz_ros2_control moves the mimic joints itself
            for axis in el.findall("axis"):
                for m in axis.findall("mimic"):
                    axis.remove(m)
            for m in el.findall("mimic"):
                el.remove(m)
        if el.tag in ("link", "joint"):
            parts.append(ET.tostring(el, encoding="unicode"))
    body = "\n    ".join(parts)
    # meshes: model://xtdrone_robotic_arm/meshes (its share directory is on GZ_SIM_RESOURCE_PATH, hooks/)
    body = re.sub(r"\n\s*\n", "\n", body)
    sdf = f"""<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by xtdrone_robotic_arm/scripts/generate_iris_arm_model.py from urdf/iris_arm.urdf.xacro. Do not edit. -->
<sdf version="1.9">
  <model name="{NAME}">
    <include merge="true">
      <uri>model://iris_legs_ardupilot</uri>
    </include>
    {body}
{PLUGINS}{ardupilot_copter_plugin()}
  </model>
</sdf>
"""
    d = OUT / NAME
    d.mkdir(parents=True, exist_ok=True)
    (d / "model.sdf").write_text(sdf)
    (d / "model.config").write_text(f"""<?xml version="1.0"?>
<model>
  <name>{NAME}</name>
  <version>1.0</version>
  <sdf version="1.9">model.sdf</sdf>
  <description>XTDrone iris (ArduPilot iris) with the le_arm robotic arm (chapter 33). Generated.</description>
</model>
""")
    (d / "xtdrone_bridge.yaml").write_text(BRIDGE)
    print(f"wrote {d}")


if __name__ == "__main__":
    main()
