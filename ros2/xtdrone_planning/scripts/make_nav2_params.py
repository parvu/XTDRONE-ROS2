#!/usr/bin/env python3
"""Write config/nav2_2d.yaml from Nav2 Jazzy's nav2_bringup/params/nav2_params.yaml (chapter 20).

Changes for an XTDrone multirotor flying at constant height on 2D laser SLAM:
  * frames: the SLAM chain is map -> odom -> base_link with a static odom -> base_link (pure scan
    matching), so the local costmap and the behaviors work in map, not odom;
  * DWB (Nav2's DWA, as move_base's dwa_local_planner in ROS 1) instead of MPPI, holonomic
    (a multirotor moves sideways), speeds from motion_planning/2d/param/dwa_local_planner_params.yaml
    raised slightly (0.4 m/s);
  * NavFn with Dijkstra (use_astar false), as the ROS 1 chapter chose;
  * robot_radius 0.4 m (iris), obstacles from /iris_0/scan.
"""
from pathlib import Path

import yaml

SRC = Path("/opt/ros/jazzy/share/nav2_bringup/params/nav2_params.yaml")
OUT = Path(__file__).resolve().parents[1] / "config" / "nav2_2d.yaml"
KEEP = ["bt_navigator", "controller_server", "local_costmap", "global_costmap", "planner_server", "behavior_server"]

d = yaml.safe_load(SRC.read_text())
d = {k: d[k] for k in KEEP}
for k in KEEP:
    p = d[k]["ros__parameters"] if "ros__parameters" in d[k] else d[k][k]["ros__parameters"]
    p["use_sim_time"] = True

bt = d["bt_navigator"]["ros__parameters"]
bt["global_frame"], bt["robot_base_frame"], bt["odom_topic"] = "map", "base_link", "/iris_0/mavros/local_position/odom"

cs = d["controller_server"]["ros__parameters"]
cs["controller_frequency"] = 10.0
cs["min_y_velocity_threshold"] = 0.001
cs["odom_topic"] = "/iris_0/mavros/local_position/odom"
cs["FollowPath"] = {
    "plugin": "dwb_core::DWBLocalPlanner",
    "debug_trajectory_details": False,
    "min_vel_x": -0.4, "min_vel_y": -0.4, "max_vel_x": 0.4, "max_vel_y": 0.4, "max_vel_theta": 0.5,
    "min_speed_xy": 0.0, "max_speed_xy": 0.4, "min_speed_theta": 0.0,
    "acc_lim_x": 1.0, "acc_lim_y": 1.0, "acc_lim_theta": 1.0,
    "decel_lim_x": -1.0, "decel_lim_y": -1.0, "decel_lim_theta": -1.0,
    "vx_samples": 15, "vy_samples": 15, "vtheta_samples": 10,
    "sim_time": 2.0, "linear_granularity": 0.05, "angular_granularity": 0.025,
    "transform_tolerance": 0.2, "xy_goal_tolerance": 0.2, "trans_stopped_velocity": 0.05,
    "short_circuit_trajectory_evaluation": True, "stateful": True,
    "critics": ["RotateToGoal", "Oscillation", "BaseObstacle", "GoalAlign", "PathAlign", "PathDist", "GoalDist"],
    "BaseObstacle.scale": 0.02, "PathAlign.scale": 0.0, "GoalAlign.scale": 0.0,
    "PathDist.scale": 32.0, "GoalDist.scale": 24.0, "RotateToGoal.scale": 32.0,
    "RotateToGoal.slowing_factor": 5.0, "RotateToGoal.lookahead_time": -1.0,
}
cs["general_goal_checker"]["xy_goal_tolerance"] = 0.2
cs["general_goal_checker"]["yaw_goal_tolerance"] = 6.28  # the chapter only asks for a position

for name in ("local_costmap", "global_costmap"):
    p = d[name][name]["ros__parameters"]
    p["global_frame"] = "map"
    p["robot_base_frame"] = "base_link"
    p["robot_radius"] = 0.4
    p.pop("footprint", None)
    p["plugins"] = ["obstacle_layer", "inflation_layer"] if name == "local_costmap" else \
        ["static_layer", "obstacle_layer", "inflation_layer"]
    p.pop("voxel_layer", None)
    p["obstacle_layer"] = {
        "plugin": "nav2_costmap_2d::ObstacleLayer", "enabled": True, "observation_sources": "scan",
        "scan": {"topic": "/iris_0/scan", "max_obstacle_height": 2.0, "clearing": True, "marking": True,
                 "data_type": "LaserScan", "raytrace_max_range": 10.0, "raytrace_min_range": 0.0,
                 "obstacle_max_range": 8.0, "obstacle_min_range": 0.0}}
    p["inflation_layer"]["inflation_radius"] = 0.7
    if name == "global_costmap":
        p["static_layer"]["map_subscribe_transient_local"] = True
        p["track_unknown_space"] = True

pl = d["planner_server"]["ros__parameters"]
pl["GridBased"]["use_astar"] = False
pl["GridBased"]["allow_unknown"] = True

bs = d["behavior_server"]["ros__parameters"]
bs["local_frame"] = "map"
bs["local_costmap_topic"] = "local_costmap/costmap_raw"

OUT.write_text("# Generated by scripts/make_nav2_params.py from nav2_bringup/params/nav2_params.yaml (Nav2 Jazzy).\n"
               + yaml.safe_dump(d, sort_keys=False))
print("wrote", OUT)
